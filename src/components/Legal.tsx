function Terms({ doc }: { doc: Doc }) {
  const n = nameOf(doc), pv = privacyOf(doc);
  return (
    <>
      <h3>제1조 (목적)</h3><p>이 약관은 {n}(이하 ‘교회’) 홈페이지를 이용하는 데 필요한 사항을 정합니다.</p>
      <h3>제2조 (약관의 효력과 변경)</h3><p>이 약관은 홈페이지에 게시하면 효력이 생깁니다. 교회는 관련 법령을 어기지 않는 범위에서 약관을 바꿀 수 있으며, 바꿀 때는 적용 7일 전부터 홈페이지에 알립니다.</p>
      <h3>제3조 (홈페이지의 제공)</h3><p>교회는 예배 안내, 설교 영상, 주보, 공지사항, 오시는 길, 새가족 등록과 문의 기능을 제공합니다. 점검이나 교회 사정에 따라 일부 기능을 잠시 멈출 수 있습니다.</p>
      <h3>제4조 (이용자의 의무)</h3><p>이용자는 문의·새가족 등록 양식에 다른 사람의 정보를 입력하거나, 홈페이지 운영을 방해해서는 안 됩니다.</p>
      <h3>제5조 (게시물의 저작권)</h3><p>홈페이지의 설교 영상, 주보, 사진, 글의 저작권은 교회 또는 원저작자에게 있습니다. 개인적인 신앙생활을 위해 보고 공유하는 것은 자유롭지만, 허락 없이 고치거나 영리 목적으로 쓸 수 없습니다.</p>
      <h3>제6조 (사진 게시 중단 요청)</h3><p>본인이 나온 사진의 게시 중단을 원하면 교회에 요청해 주세요. 확인한 뒤 지체 없이 내립니다.</p>
      <h3>제7조 (개인정보 보호)</h3><p>교회는 개인정보처리방침에 따라 이용자의 개인정보를 보호합니다.</p>
      <h3>제8조 (책임의 제한)</h3><p>교회는 천재지변, 통신 장애처럼 교회가 막을 수 없는 사유로 생긴 이용 장애에 대해서는 책임을 지지 않습니다. 홈페이지에서 연결한 외부 서비스(유튜브, 지도 앱 등)의 이용은 각 서비스의 정책을 따릅니다.</p>
      <h3>제9조 (분쟁 해결)</h3><p>홈페이지 이용과 관련한 분쟁은 서로 성실히 협의해 해결하며, 협의가 되지 않으면 관련 법령에 따릅니다.</p>
      <p className="doc-eff">부칙: 이 약관은 {md(pv.effective)}부터 시행합니다.</p>
    </>
  );
}

export const DOC_TITLE: Record<DocKind, string> = { privacy: '개인정보처리방침', terms: '이용약관' };

export function LegalDoc({ kind, doc }: { kind: DocKind; doc: Doc }) {
  return <article className="doc-page">{kind === 'privacy' ? <Privacy doc={doc} /> : <Terms doc={doc} />}</article>;
}
